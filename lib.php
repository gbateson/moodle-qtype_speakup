/**
 * Checks file access for qtype_speakup. Serves files from the 'audioprompt'
 * file area (set on the editing form) and, later, the 'response_audio' file
 * area (the student's recorded answer, stored against the question_attempt).
 *
 * @category files
 *
 * @param stdClass $course course object
 * @param stdClass $cm course module object
 * @param context $context context object
 * @param string $filearea file area
 * @param array $args extra arguments
 * @param bool $forcedownload whether or not force download
 * @param array $options additional options affecting the file serving
 * @return bool false if file not found, does not return if found - just send the file
 */
function qtype_speakup_pluginfile($course, $cm, $context, $filearea, $args, $forcedownload, array $options = []) {
    global $CFG;
    require_once($CFG->libdir . '/questionlib.php');
    question_pluginfile($course, $context, 'qtype_speakup', $filearea, $args, $forcedownload, $options);
}
